namespace GameJam.Data
{
    /// <summary>
    /// 属性 ID —— 三属性（炼金三元素）。
    ///
    /// 【为什么是 3 个而不是 6 个】
    /// 旧版是 6 个按"厨房直觉"起的属性（硬度/温度/酸性/糖分/油脂/水分），
    /// 数值策划定稿后改成炼金三元素体系：
    ///
    ///     H 盐性 —— 固体倾向 —— 耐久、生命值
    ///     D 汞性 —— 液体倾向 —— 溶解力、流动性、催化力
    ///     V 硫性 —— 气体倾向 —— 挥发性、膨胀力、压力
    ///
    /// 三者是一条转化链：固态 --(D)--> 溶液 --(V)--> 气体。
    /// 所以"温度/酸性"这类独立维度被合并掉了 —— 它们本来就是
    /// "往哪个方向转化"的不同说法。
    ///
    /// 字母代号 H / D / V 沿用策划文档，不要改成 Salt/Mercury/Sulfur 的首字母，
    /// 界面和文案都按 H/D/V 称呼。
    ///
    /// 数值必须连续从 0 开始 —— AttrSet 用 (int)AttrId 当下标。
    /// </summary>
    public enum AttrId
    {
        /// <summary>H 盐性 —— 固体倾向。耐久、生命值。归零则固态原材变粉末；刀片归零爆刀。</summary>
        Salt    = 0,

        /// <summary>D 汞性 —— 液体倾向。溶解力、流动性、催化力。</summary>
        Mercury = 1,

        /// <summary>V 硫性 —— 气体倾向。挥发性、膨胀力、压力。</summary>
        Sulfur  = 2,
    }
}
